package StatementConduction;

public class IfElseIFExample {

    public static void main(String[] args) {
        int mark=80;

        if(mark>90){
            System.out.println("A Gread");
        }else if (mark>70){
            System.out.println("B gread");
        } else if (mark>50) {
            System.out.println("C gread");
        }
        else {
            System.out.println("fail");
        }
    }

}
